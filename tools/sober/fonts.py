"""Convert TTF/OTF fonts into Adafruit GFX fonts (and keep them in memory for the preview)."""
import json
import os
from dataclasses import dataclass, field

from PIL import Image, ImageDraw, ImageFont


EXTRA = ["\u00b7", "\u2014", "\u25cf", "\u25b2", "\u25bc"]  # extra glyphs at codes 127..131: middle dot, em dash, dot, up and down triangles (up / down buttons)


def to_device(s):
    """Map the extra typographic characters to their device codes."""
    for i, ch in enumerate(EXTRA):
        s = s.replace(ch, chr(127 + i))
    return s


@dataclass
class Glyph:
    offset: int
    width: int
    height: int
    x_advance: int
    x_offset: int
    y_offset: int
    bits: list  # rows of 0/1, height x width


@dataclass
class GfxFont:
    name: str
    first: int
    last: int
    y_advance: int
    glyphs: list
    bitmap: bytearray
    ascent: int = 0
    descent: int = 0

    @property
    def cname(self):
        return "font_" + self.name.replace("-", "_")

    def glyph(self, ch):
        c = ord(ch)
        if c < self.first or c > self.last:
            c = ord("?") if self.first <= ord("?") <= self.last else self.first
        return self.glyphs[c - self.first]

    def advance(self, ch):
        return self.glyph(ch).x_advance

    def text_width(self, s):
        return sum(self.advance(ch) for ch in s)


def _load(path, size, weight=None):
    font = ImageFont.truetype(path, size)
    if weight is not None:
        try:
            font.set_variation_by_axes([weight])
        except Exception:
            pass
    return font


# Hand spacing fixes: (font name, character) -> (pixels to move the glyph right, pixels to add to its advance).
NUDGE = {("small-b", "v"): (2, 1)}  # touched the d in "adventure" (landing page): a clear pixel each side now


def convert(spec, font_dir):
    path = os.path.join(font_dir, spec["file"])
    size = spec["size"]
    font = _load(path, size, spec.get("weight"))
    chars = spec.get("chars")
    first, last = 32, 126 + len(EXTRA)
    wanted = set(chars) if chars else None
    mono = spec.get("mono", False)
    glyphs = []
    bitmap = bytearray()
    for code in range(first, last + 1):
        ch = chr(code) if code < 127 else EXTRA[code - 127]
        adv = int(round(font.getlength(ch))) + (spec.get("spacing", 0) if ch != " " else 0)
        if wanted is not None and ch not in wanted:
            glyphs.append(Glyph(len(bitmap), 0, 0, 0, 0, 0, []))
            continue
        pad = size * 2
        canvas = Image.new("L", (size * 4 + pad, size * 4 + pad), 0)
        d = ImageDraw.Draw(canvas)
        d.fontmode = "1" if mono else "L"
        ox, oy = pad, size * 3
        d.text((ox, oy), ch, font=font, fill=255, anchor="ls")
        bw = canvas.point(lambda v: 255 if v >= 128 else 0)
        box = bw.getbbox()
        if box is None or ch == " ":
            glyphs.append(Glyph(len(bitmap), 0, 0, adv, 0, 0, []))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        rows = [[1 if bw.getpixel((x0 + x, y0 + y)) else 0 for x in range(w)] for y in range(h)]
        offset = len(bitmap)
        acc, n = 0, 0
        for row in rows:
            for b in row:
                acc = (acc << 1) | b
                n += 1
                if n == 8:
                    bitmap.append(acc)
                    acc, n = 0, 0
        if n:
            bitmap.append(acc << (8 - n))
        dx, dadv = NUDGE.get((spec["name"], ch), (0, 0))
        glyphs.append(Glyph(offset, w, h, adv + dadv, x0 - ox + dx, y0 - oy, rows))
    ascent_font, descent_font = font.getmetrics()
    gf = GfxFont(spec["name"], first, last, ascent_font + descent_font, glyphs, bitmap)
    # Visual ascent/descent used for vertical centring: cap/digit height and descender depth.
    caps = [g for c, g in zip(range(first, last + 1), glyphs) if chr(c) in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789" and g.height]
    desc = [g for c, g in zip(range(first, last + 1), glyphs) if chr(c) in "gjpqy" and g.height]
    gf.ascent = max((-g.y_offset for g in caps), default=size)
    gf.descent = max((g.y_offset + g.height for g in desc), default=0)
    return gf


def load_all(root):
    font_dir = os.path.join(root, "fonts")
    with open(os.path.join(font_dir, "fonts.json")) as f:
        specs = json.load(f)["fonts"]
    return [convert(s, font_dir) for s in specs]


def emit_header(fonts):
    out = ["// Generated by tools/build_ui.py from fonts/fonts.json. Do not edit.",
           "#pragma once", "#include <Adafruit_GFX.h>", ""]
    for gf in fonts:
        out.append(f"static const uint8_t {gf.cname}_bitmap[] PROGMEM = {{")
        data = gf.bitmap or bytearray([0])
        for i in range(0, len(data), 16):
            out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const GFXglyph {gf.cname}_glyphs[] PROGMEM = {{")
        for i, g in enumerate(gf.glyphs):
            out.append(f"  {{{g.offset}, {g.width}, {g.height}, {g.x_advance}, {g.x_offset}, {g.y_offset}}}, // code {gf.first + i}")
        out.append("};")
        out.append(f"static const GFXfont {gf.cname} PROGMEM = {{(uint8_t*){gf.cname}_bitmap, (GFXglyph*){gf.cname}_glyphs, {gf.first}, {gf.last}, {gf.y_advance}}};")
        out.append("")
    out.append("struct UiFontInfo { const GFXfont* font; int8_t ascent; int8_t descent; uint8_t lineHeight; };")
    out.append("static const UiFontInfo UI_FONTS[] = {")
    for gf in fonts:
        out.append(f"  {{&{gf.cname}, {gf.ascent}, {gf.descent}, {gf.y_advance}}}, // {gf.name}")
    out.append("};")
    out.append(f"static const uint8_t UI_FONT_COUNT = {len(fonts)};")
    for i, gf in enumerate(fonts):
        out.append(f"#define UI_FONT_{gf.name.upper().replace('-', '_')} {i}")
    return "\n".join(out) + "\n"
