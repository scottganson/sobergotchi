"""Turn SVG/PNG artwork into 1-bit bitmaps for the e-paper screen.

SVG convention: put line work in <g id="ink"> and grey shading in <g id="shade">.
Ink is thresholded (crisp lines). Shade greys become ordered-dither textures:
light grey = sparse dots, mid grey = checkerboard, dark grey = dense.
"""
import glob
import json
import os
import subprocess
import tempfile
from dataclasses import dataclass

from PIL import Image

BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
GROUP_DIRS = ["tree", "rps"]          # each of these folders becomes an indexed group (frames)
SINGLE_DIRS = ["icons", "legacy"]  # each file in these is its own image
SCALE = 4


@dataclass
class Art:
    name: str
    width: int
    height: int
    rows: list  # height x width of 0/1 (1 = ink)

    @property
    def cname(self):
        return "art_" + self.name.replace("-", "_")


def dither_level(v):
    """Grey 0..255 -> number of inked cells out of 16, snapped to 5 clean textures."""
    ink = (255 - v) / 255.0
    levels = [0, 2, 4, 8, 12, 16]
    target = ink * 16
    return min(levels, key=lambda l: abs(l - target))


def _downsample(img, w, h):
    return img.convert("L").resize((w, h), Image.BOX)


def _svg_size(path):
    import re
    txt = open(path, encoding="utf8").read()
    m_w = re.search(r'<svg[^>]*\swidth="([\d.]+)"', txt)
    m_h = re.search(r'<svg[^>]*\sheight="([\d.]+)"', txt)
    return int(float(m_w.group(1))), int(float(m_h.group(1)))


def rasterize_svgs(paths, root):
    """Return {path: (ink_img, shade_img)} greyscale images at 1x."""
    if not paths:
        return {}
    tmp = tempfile.mkdtemp(prefix="sober_art_")
    jobs, out = [], {}
    for i, p in enumerate(paths):
        jobs.append({"svg": p, "png": os.path.join(tmp, f"{i}_ink.png"), "scale": SCALE, "hide": "shade"})
        jobs.append({"svg": p, "png": os.path.join(tmp, f"{i}_shade.png"), "scale": SCALE, "hide": "ink"})
    jf = os.path.join(tmp, "jobs.json")
    with open(jf, "w") as f:
        json.dump(jobs, f)
    # Needs Node.js with the "playwright" package (npm install playwright; npx playwright install chromium).
    subprocess.run(["node", os.path.join(root, "tools", "rasterize.js"), jf], check=True)
    for i, p in enumerate(paths):
        w, h = _svg_size(p)
        ink = _downsample(Image.open(os.path.join(tmp, f"{i}_ink.png")), w, h)
        shade = _downsample(Image.open(os.path.join(tmp, f"{i}_shade.png")), w, h)
        out[p] = (ink, shade)
    return out


def to_bits(ink_img, shade_img=None):
    w, h = ink_img.size
    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            on = ink_img.getpixel((x, y)) < 128
            if not on and shade_img is not None:
                lvl = dither_level(shade_img.getpixel((x, y)))
                on = BAYER4[y & 3][x & 3] < lvl
            row.append(1 if on else 0)
        rows.append(row)
    return rows


def load_png(path):
    img = Image.open(path).convert("L")
    return to_bits(img)


def build(root):
    art_dir = os.path.join(root, "art")
    singles, groups = [], []
    svg_paths = []
    for d in SINGLE_DIRS + GROUP_DIRS:
        svg_paths += sorted(glob.glob(os.path.join(art_dir, d, "*.svg")))
    rendered = rasterize_svgs(svg_paths, root)

    def make(path):
        name = os.path.splitext(os.path.basename(path))[0]
        if path.endswith(".svg"):
            ink, shade = rendered[path]
            rows = to_bits(ink, shade)
        else:
            rows = load_png(path)
        return Art(name, len(rows[0]), len(rows), rows)

    for d in SINGLE_DIRS:
        for p in sorted(glob.glob(os.path.join(art_dir, d, "*.svg")) + glob.glob(os.path.join(art_dir, d, "*.png"))):
            singles.append(make(p))
    for d in GROUP_DIRS:
        frames = [make(p) for p in sorted(glob.glob(os.path.join(art_dir, d, "*.svg")) + glob.glob(os.path.join(art_dir, d, "*.png")))]
        for i, fr in enumerate(frames):
            fr.name = f"{d}_{i:02d}"
        groups.append((d, frames))
    return singles, groups


def emit_header(singles, groups):
    out = ["// Generated by tools/build_ui.py from art/. Do not edit.", "#pragma once", "#include <Arduino.h>", "",
           "struct UiArt { const uint8_t* data; uint8_t w; uint8_t h; };", ""]
    all_art = list(singles) + [fr for _, frames in groups for fr in frames]
    for a in all_art:
        bpr = (a.width + 7) // 8
        data = bytearray()
        for row in a.rows:
            for bx in range(bpr):
                b = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    b = (b << 1) | (row[x] if x < a.width else 0)
                data.append(b)
        out.append(f"static const uint8_t {a.cname}[] PROGMEM = {{")
        for i in range(0, len(data), 16):
            out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};")
    out.append("")
    out.append("static const UiArt UI_ART[] = {")
    for a in all_art:
        out.append(f"  {{{a.cname}, {a.width}, {a.height}}},")
    out.append("};")
    idx = 0
    for a in singles:
        out.append(f"#define ART_{a.name.upper().replace('-', '_')} {idx}")
        idx += 1
    for name, frames in groups:
        out.append(f"#define ART_GROUP_{name.upper()} {idx}")
        out.append(f"#define ART_GROUP_{name.upper()}_COUNT {len(frames)}")
        idx += len(frames)
    return "\n".join(out) + "\n"


def index_map(singles, groups):
    """name -> (first index, count) used by the screen compiler and preview."""
    m, idx = {}, 0
    for a in singles:
        m[a.name] = (idx, 1)
        idx += 1
    for name, frames in groups:
        m[name] = (idx, len(frames))
        idx += len(frames)
    flat = list(singles) + [fr for _, frames in groups for fr in frames]
    return m, flat
