#!/usr/bin/env python3
"""Build everything the firmware draws, from the files people edit.

  fonts/fonts.json + fonts/*.ttf   -> firmware/sobergotchi/src/generated/fonts.h
  art/**/*.svg|png                 -> firmware/sobergotchi/src/generated/art.h
  screens/*.sml                    -> firmware/sobergotchi/src/generated/screens.h
  content/reflections.json         -> firmware/sobergotchi/src/generated/reflections.h
  and a true-size + 3x PNG preview of every screen in preview/

Usage:  python tools/build_ui.py            (build all + previews)
        python tools/build_ui.py --preview  (previews only, nothing written to firmware)
Needs:  Python 3.9+, Pillow; Node.js + playwright for SVG art.
"""
import argparse
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from sober import fonts as F  # noqa: E402
from sober import art as A  # noqa: E402
from sober import sml as S  # noqa: E402
from sober.render import Renderer, SampleData  # noqa: E402
from PIL import Image  # noqa: E402

GEN = os.path.join(ROOT, "firmware", "sobergotchi", "src", "generated")
PREVIEW = os.path.join(ROOT, "preview")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path, encoding="utf8").read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="utf8", newline="\n") as f:
            f.write(text)
        print("  wrote", os.path.relpath(path, ROOT))


def emit_reflections():
    with open(os.path.join(ROOT, "content", "reflections.json"), encoding="utf8") as f:
        items = json.load(f)["reflections"]
    out = ["// Generated by tools/build_ui.py from content/reflections.json. Do not edit.", "#pragma once", "",
           "struct Reflection { const char* title; const char* text; };",
           f"static const Reflection REFLECTIONS[{len(items)}] = {{"]
    for it in items:
        text = it["text"].strip()
        if len(text) > 1 and text[0] == '"' and text[-1] == '"':
            text = text[1:-1]  # the screen draws its own quote mark
        out.append(f'  {{{S.c_str(F.to_device(it["title"]))}, {S.c_str(F.to_device(text))}}},')
    out.append("};")
    out.append(f"static const uint16_t REFLECTION_COUNT = {len(items)};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true", help="only render previews")
    ap.add_argument("--screen", help="only this screen id")
    args = ap.parse_args()

    print("fonts...")
    fonts = F.load_all(ROOT)
    print("art...")
    singles, groups = A.build(ROOT)
    art_index, art_flat = A.index_map(singles, groups)
    print("screens...")
    layout = S.Layout(fonts, art_index, art_flat)
    screens = []
    for path in sorted(glob.glob(os.path.join(ROOT, "screens", "*.sml"))):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding="utf8") as f:
            try:
                screens.append(S.compile_screen(f.read(), name, layout))
            except S.SmlError as e:
                sys.exit(f"error in screens/{name}.sml: {e}")

    if not args.preview:
        write(os.path.join(GEN, "fonts.h"), F.emit_header(fonts))
        write(os.path.join(GEN, "art.h"), A.emit_header(singles, groups))
        write(os.path.join(GEN, "screens.h"), S.emit_header(screens))
        write(os.path.join(GEN, "reflections.h"), emit_reflections())

    print("previews...")
    with open(os.path.join(ROOT, "tools", "preview_data.json"), encoding="utf8") as f:
        sample = json.load(f)
    r = Renderer(fonts, art_flat)
    os.makedirs(PREVIEW, exist_ok=True)
    for sid, recs in screens:
        if args.screen and sid != args.screen:
            continue
        variants = sample.get("_variants", {}).get(sid, [{}])
        for k, override in enumerate(variants):
            data = dict(sample)
            data.update(override)
            img = r.draw(recs, SampleData(data)).img
            suffix = "" if len(variants) == 1 else f"-{k + 1}"
            img.save(os.path.join(PREVIEW, f"{sid}{suffix}.png"))
            big = img.convert("L").resize((img.width * 3, img.height * 3), Image.NEAREST)
            big.save(os.path.join(PREVIEW, f"{sid}{suffix}@3x.png"))
    # Tree stages contact sheet
    if "tree" in art_index:
        first, count = art_index["tree"]
        cols = 7
        aw, ah = art_flat[first].width, art_flat[first].height
        sheet = Image.new("1", (cols * (aw + 4), ((count + cols - 1) // cols) * (ah + 4)), 1)
        for k in range(count):
            a = art_flat[first + k]
            im = Image.new("1", (a.width, a.height), 1)
            for y, row in enumerate(a.rows):
                for x, b in enumerate(row):
                    if b:
                        im.putpixel((x, y), 0)
            sheet.paste(im, ((k % cols) * (aw + 4), (k // cols) * (ah + 4)))
        sheet.convert("L").resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(os.path.join(PREVIEW, "tree-stages@2x.png"))
    print("done")


if __name__ == "__main__":
    main()
